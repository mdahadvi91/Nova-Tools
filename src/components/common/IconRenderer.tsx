interface IconRendererProps extends LucideProps {
  name?: string;
  iconName?: string;
}

export const IconRenderer: React.FC<IconRendererProps> = ({ name, iconName, ...props }) => {
  const resolvedName = iconName || name || '';
  const IconComponent = iconMap[resolvedName] || Wrench;
  return <IconComponent {...props} />;
};
